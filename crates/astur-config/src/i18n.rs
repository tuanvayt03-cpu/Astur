use std::path::Path;
use std::sync::atomic::{AtomicBool, Ordering};

#[cfg(test)]
pub(crate) static TEST_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());

static VIETNAMESE: AtomicBool = AtomicBool::new(false);

pub fn language() -> &'static str {
    if VIETNAMESE.load(Ordering::Relaxed) {
        "vi"
    } else {
        "en"
    }
}

pub fn set_language(lang: &str) {
    VIETNAMESE.store(lang == "vi", Ordering::Relaxed);
}

pub fn load(path: &Path) {
    let value = std::fs::read_to_string(path).unwrap_or_else(|_| "vi".to_owned());
    set_language(value.trim());
}

pub fn save(path: &Path, lang: &str) -> std::io::Result<()> {
    if !matches!(lang, "en" | "vi") {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            "unsupported locale",
        ));
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, lang.as_bytes())?;
    set_language(lang);
    Ok(())
}

