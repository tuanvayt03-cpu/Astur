#[cfg(test)]
mod tests {
    use super::*;
    static TEST_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());
    #[test]
    fn default_locale_english_and_vietnamese_fallback() {
        let _lock = TEST_LOCK.lock().unwrap();
        set_language("en");
        assert_eq!(tr("Home"), "Home");
        set_language("vi");
        assert_eq!(tr("Home"), "Trang chủ");
        assert_eq!(
            tr("some future upstream field"),
            "some future upstream field"
        );
        set_language("en");
    }
    #[test]
    fn only_known_locales_enable_vietnamese() {
        let _lock = TEST_LOCK.lock().unwrap();
        set_language("vi");
        assert_eq!(language(), "vi");
        set_language("xyz");
        assert_eq!(language(), "en");
    }
    #[test]
    fn missing_locale_pref_defaults_to_vietnamese() {
        let _lock = TEST_LOCK.lock().unwrap();
        let path = std::env::temp_dir().join(format!(
            "missing-astur-vi-locale-{}.txt",
            std::process::id()
        ));
        let _ = std::fs::remove_file(&path);
        set_language("en");
        load(&path);
        assert_eq!(language(), "vi");
        set_language("en");
    }
    #[test]
    fn locale_preference_is_separate_from_legacy_configs() {
        let _lock = TEST_LOCK.lock().unwrap();
        let path = std::env::temp_dir().join(format!("astur-vi-locale-{}.txt", std::process::id()));
        save(&path, "vi").unwrap();
        set_language("en");
        load(&path);
        assert_eq!(language(), "vi");
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "vi");
        assert!(save(&path, "xx").is_err());
        let _ = std::fs::remove_file(path);
        set_language("en");
    }
}
